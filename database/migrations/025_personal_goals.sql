CREATE TABLE goals (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 owner_user_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(190) NOT NULL,
 description TEXT NOT NULL,
 status ENUM('active','completed') NOT NULL DEFAULT 'active',
 target_date DATE NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX goals_owner(owner_user_id),
 FOREIGN KEY(owner_user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE goal_tasks (
 goal_id BIGINT UNSIGNED NOT NULL,
 task_id BIGINT UNSIGNED NOT NULL,
 PRIMARY KEY(goal_id,task_id),
 FOREIGN KEY(goal_id) REFERENCES goals(id) ON DELETE CASCADE,
 FOREIGN KEY(task_id) REFERENCES calendar_tasks(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE goal_habits (
 goal_id BIGINT UNSIGNED NOT NULL,
 habit_id BIGINT UNSIGNED NOT NULL,
 PRIMARY KEY(goal_id,habit_id),
 FOREIGN KEY(goal_id) REFERENCES goals(id) ON DELETE CASCADE,
 FOREIGN KEY(habit_id) REFERENCES habits(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE goal_cards (
 goal_id BIGINT UNSIGNED NOT NULL,
 item_id BIGINT UNSIGNED NOT NULL,
 card_key VARCHAR(36) NOT NULL,
 completed_on DATE NULL,
 PRIMARY KEY(goal_id,item_id,card_key),
 FOREIGN KEY(goal_id) REFERENCES goals(id) ON DELETE CASCADE,
 FOREIGN KEY(item_id) REFERENCES mindspace_items(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
